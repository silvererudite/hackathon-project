#!/usr/bin/env python
"""
Human analyst vs LLM agent, step by step, on the identical task.

    python compare_trajectories.py test5
    python compare_trajectories.py test4          # the interesting one
    python compare_trajectories.py --all

The HUMAN column is the reference trajectory a careful analyst takes: look at
the data, run the sweep as asked, find who is careless, exclude them, re-run,
plot. It is generated by sciops_agent.scripted_correlates and is deterministic.

The AGENT column is what the model actually did, read from its recorded trace.

Aligning them by ANALYTICAL STEP rather than by turn number is the point. Two
runs can reach the same number having done different work, and the only place
that is visible is here.
"""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
B, D, R, G, Y, C, X = ("\033[1m", "\033[2m", "\033[31m", "\033[32m",
                       "\033[33m", "\033[36m", "\033[0m")

# The analytical beats a competent analysis hits, in order.
BEATS = [
    ("inspect",   "1 inspect data",     ["describe_dataset", "inspect_data"]),
    ("baseline",  "2 sweep as asked",   ["correlation_sweep"]),
    ("detect",    "3 find careless",    ["flag_careless_subjects"]),
    ("exclude",   "4 re-run excluding", ["correlation_sweep"]),
    ("report",    "5 plot / conclude",  ["plot_correlation_matrix"]),
]


def read_trace(path: Path) -> list[dict]:
    t = json.loads(path.read_text())
    out = []
    for s in t["trace"]:
        try:
            args = json.loads(s["action"].get("input") or "{}")
        except json.JSONDecodeError:
            args = {}
        obs = s.get("observation") or ""
        out.append({
            "tool": s["action"].get("tool") or s["action"]["type"],
            "phase": s["phase"], "thought": s.get("thought") or "",
            "confidence": s.get("confidence"),
            "n_excluded_passed": len(args.get("exclude_subjects") or []),
            "n_flagged": int(m.group(1)) if (m := re.search(r'"n_flagged": (\d+)', obs)) else None,
            "n_excluded_applied": int(m.group(1)) if (m := re.search(r'"n_subjects_excluded": (\d+)', obs)) else None,
            "n_significant": int(m.group(1)) if (m := re.search(r'"n_significant": (\d+)', obs)) else None,
        })
    return out, (t.get("outcome") or {}), t.get("model", "?")


def align(steps: list[dict]) -> dict:
    """Map recorded steps onto the analytical beats."""
    hit = {k: None for k, _, _ in BEATS}
    seen_sweep = 0
    for s in steps:
        for key, _, tools in BEATS:
            if s["tool"] not in tools:
                continue
            if key == "baseline":
                if s["tool"] == "correlation_sweep" and not s["n_excluded_passed"]:
                    hit["baseline"] = hit["baseline"] or s
                continue
            if key == "exclude":
                if s["tool"] == "correlation_sweep" and s["n_excluded_passed"]:
                    hit["exclude"] = hit["exclude"] or s
                continue
            hit[key] = hit[key] or s
    return hit


def human_trajectory(condition: str):
    """Run the reference analyst path and read its trace."""
    import sciops_agent as A
    from trace_schema import Trajectory, TrajectoryMetadata, now_iso
    A.reset()
    A.TRACE = Trajectory(trajectory_id=f"{condition}_human", prompt=condition,
                         model="reference analyst",
                         metadata=TrajectoryMetadata(collection_timestamp=now_iso()))
    A.scripted_correlates(condition, verbose=False)
    A.TRACE.recompute_metadata()
    tmp = HERE / "outputs" / f"{condition}_human_trace.json"
    tmp.parent.mkdir(exist_ok=True)
    tmp.write_text(A.TRACE.model_dump_json(indent=1))
    return read_trace(tmp)


def cell(s: dict | None, width: int) -> list[str]:
    if s is None:
        return [f"{R}not done{X}".ljust(width + 9)]
    bits = []
    n = s["tool"] or "-"
    bits.append(f"{C}{n[:width]}{X}".ljust(width + 9))
    detail = []
    if s["n_flagged"] is not None:
        detail.append(f"flagged {s['n_flagged']}")
    if s["n_excluded_applied"] is not None and s["n_excluded_passed"]:
        detail.append(f"excluded {s['n_excluded_applied']}")
    if s["n_significant"] is not None:
        detail.append(f"{s['n_significant']}/63 sig")
    if s["confidence"] is not None:
        detail.append(f"conf {s['confidence']}")
    if detail:
        bits.append(f"{D}{', '.join(detail)[:width]}{X}".ljust(width + 9))
    return bits


def compare(condition: str, traces_dir: str):
    hits = [p for p in sorted(Path(traces_dir).glob(f"{condition}_*trace.json"))
            if "scripted" not in p.name and "human" not in p.name]
    if not hits:
        print(f"{R}no agent trace for {condition}{X}")
        return
    a_steps, a_out, model = read_trace(hits[0])
    h_steps, h_out, _ = human_trajectory(condition)
    A_, H_ = align(a_steps), align(h_steps)

    W = 34
    print()
    print(f"  {B}{condition.upper()}{X}   human analyst  vs  {model}")
    print(f"  {D}{'─' * 92}{X}")
    print(f"    {'':<19} {B}{'HUMAN (reference)':<{W}}{X} {B}AGENT{X}")
    print(f"  {D}{'─' * 92}{X}")

    divergence = []
    for key, label, _ in BEATS:
        h, a = H_[key], A_[key]
        hl, al = cell(h, W - 2), cell(a, W - 2)
        same = (h is None) == (a is None)
        mark = " " if same else f"{R}!{X}"
        print(f"  {mark} {label:<19} {hl[0]:<{W+9}} {al[0]}")
        for i in range(1, max(len(hl), len(al))):
            lh = hl[i] if i < len(hl) else "".ljust(W + 9)
            la = al[i] if i < len(al) else ""
            print(f"    {'':<19} {lh:<{W+9}} {la}")
        if not same:
            divergence.append(label)

    print(f"  {D}{'─' * 92}{X}")
    hc = (h_out.get("final_claim") or "")[:150]
    ac = (a_out.get("final_claim") or "")[:150]
    print(f"\n  {B}HUMAN concluded{X}  {hc}")
    print(f"\n  {B}AGENT concluded{X}  {ac}")
    print()
    if divergence:
        print(f"  {R}{B}DIVERGED AT: {', '.join(divergence)}{X}")
        if "4 re-run excluding" in divergence:
            print(f"  {D}   The agent identified careless subjects and never removed them.{X}")
            print(f"  {D}   Its conclusion still describes the exclusion.{X}")
    else:
        print(f"  {G}{B}Same analytical path.{X}")
    print()


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("condition", nargs="?", default="test5")
    ap.add_argument("--traces", default="outputs 2")
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    conds = ["baseline", "test1", "test2", "test3", "test4", "test5"] if a.all else [a.condition]
    for c in conds:
        compare(c, a.traces)
